const stripAccents = (s: string): string =>
  s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()

export function matchCuratedPlaces(query: string, limit = 8): { name: string; lat: number; lng: number }[] {
  const q = stripAccents(query.trim())
  if (!q) return []
  const starts: CuratedPlace[] = []
  const contains: CuratedPlace[] = []
  for (const p of CURATED_PLACES) {
    const n = stripAccents(p.name)
    if (n.startsWith(q)) starts.push(p)
    else if (n.includes(q)) contains.push(p)
    if (starts.length >= limit) break
  }
  return [...starts, ...contains].slice(0, limit).map(({ name, lat, lng }) => ({ name, lat, lng }))
}
